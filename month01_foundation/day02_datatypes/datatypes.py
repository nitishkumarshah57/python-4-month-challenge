# Day 02 - Data Types
# Topic: int, float, string, boolean, type()

age = 19              # int
height = 5.9          # float
name = "Nitish"       # string
is_student = True     # boolean

print(age, type(age))
print(height, type(height))
print(name, type(name))
print(is_student, type(is_student))
