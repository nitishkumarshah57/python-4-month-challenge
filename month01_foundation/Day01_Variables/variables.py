# Integer variable
age = 19

# Float variable
height = 5.9

# String variable
name = "Nitish"

# Boolean variable
is_student = True

print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is Student:", is_student)

# Changing value
age = age + 1
print("Updated Age:", age)
